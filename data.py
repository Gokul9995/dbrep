def parse_data(data):
  """Parses the given Tamil text data and returns a list of JSON objects.

  Args:
    data: A list of strings, where each string represents an entry.

  Returns:
    A list of JSON objects, each containing 'name', 'address', and 'amount' fields.
  """

  result = []
  for entry in data:
    # Remove the serial number if present
    entry = re.sub(r"^\d+\.\s*", "", entry)

    # Split the entry into words
    words = entry.split()

    # Find the name
    name_pattern = r"^(திரு|திருமதி|திருமிகு)\s*(\w+\s*)+"
    name_match = re.search(name_pattern, entry)
    name = name_match.group(0) if name_match else " ".join(words[:2])

    # Find the address
    address_start = entry.find("S/O")
    if address_start == -1:
      address_start = entry.find("W/O")
    if address_start == -1:
      address_start = entry.find("d/o")
    if address_start != -1:
      address_end = entry.find("ரூ")
      if address_end != -1:
        address = entry[address_start:address_end].strip()
      else:
        address = entry[address_start:].strip()
    else:
      # If no "S/O", "W/O", or "d/o" found, search for the first occurrence of "ரூ"
      address_end = entry.find("ரூ")
      if address_end != -1:
        address = " ".join(words[2:address_end])
      else:
        address = " ".join(words[2:])

    # Find the amount
    amount_pattern = r"ரூ\s*(\d+)"
    amount_match = re.search(amount_pattern, entry)
    amount = int(amount_match.group(1)) if amount_match else 501  # Default to 501 if not found

    result.append({"name": name, "address": address, "amount": amount})

  return result


